// The four difficulties, easiest to hardest.
// Each value is also how many stars clearing a level on it is worth, so (int)Temperament.Violence == 3.
// If the star rules change, change the numbers here and everything else follows.
public enum Temperament
{
    Annoyance = 1,
    Anger = 2,
    Violence = 3,
    Bloodlust = 4
}
